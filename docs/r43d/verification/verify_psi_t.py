import numpy as np
np.random.seed(0)

# Уравнение из файла (Фаза 5):
# Ψ(t) = [Ψ0 + αξ/(1+εS) + Σ ρn Φn(t) sin(θn+δn t)] / [1 + ε|Φ''| + μ|Φ'|]

dt = 0.001
t = np.arange(0, 10, dt)

# ---------- ФАКТ 1: уравнение ТРЕБУЕТ производных Φ ----------
print("="*68)
print("ФАКТ 1: содержит ли уравнение производные? (заявлено: 'Нет ∂')")
print("  Знаменатель = 1 + ε·|d²Φ/dt²| + μ·|dΦ/dt|")
print("  => для вычисления Ψ ОБЯЗАТЕЛЬНО нужны 1-я и 2-я производные Φ.")
print("  'Не содержит дифференцирования самого Ψ' — верно, но Φ дифференцируется ДВАЖДЫ.")
print("  ВЕРДИКТ: уравнение НЕ свободно от производных. Заявление ложно.\n")

# ---------- ФАКТ 2: 2-я производная катастрофически усиливает шум ----------
print("="*68)
print("ФАКТ 2: устойчивость маски на ШУМНОМ (хаотичном) сигнале")
# чистый сигнал + шум (хаос, как во 'Фаза 1')
clean = np.sin(2*np.pi*0.5*t) + 0.5*np.sin(2*np.pi*1.3*t)
noise = 0.05*np.random.randn(len(t))      # всего 5% шума
Phi = clean + noise
d1 = np.gradient(Phi, dt)
d2 = np.gradient(d1, dt)
d1c = np.gradient(clean, dt); d2c = np.gradient(d2c if False else np.gradient(clean,dt), dt)
print(f"  std(Φ) с 5% шума        : {Phi.std():.3f}")
print(f"  std(Φ')  чистый / шумный: {d1c.std():.2f} / {d1.std():.2f}  (x{d1.std()/d1c.std():.0f})")
print(f"  std(Φ'') чистый / шумный: {d2c.std():.2f} / {d2.std():.2f}  (x{d2.std()/d2c.std():.0f})")
print("  => 2-я производная раздувает 5% шума в СОТНИ раз. Маска 1/(1+ε|Φ''|)")
print("     управляется не сигналом, а шумом. 'Стабилизатор' стоит на самой")
print("     неустойчивой в численности операции. Это фактический дефект.\n")

# ---------- ФАКТ 3: что реально делает Ψ(t) ----------
print("="*68)
print("ФАКТ 3: поведение Ψ(t) — что выдаёт формула")
Psi0, alpha, xi, eps, mu = 1.0, 0.3, 0.2, 0.1, 0.1
S = 0.8; rho = 1.2; theta0, delta = 0.0, 2.0
num = Psi0 + alpha*xi/(1+eps*S) + rho*Phi*np.sin(theta0+delta*t)
den = 1 + eps*np.abs(d2) + mu*np.abs(d1)
Psi = num/den
print(f"  Ψ(t): min={Psi.min():.3f} max={Psi.max():.3f} mean={Psi.mean():.3f} std={Psi.std():.3f}")
# корреляция: где |Φ''| велико -> Ψ подавлен?
corr = np.corrcoef(np.abs(d2), 1/den)[0,1]
print(f"  corr(|Φ''|, 1/знаменатель) = {corr:.3f}  (отрицательная => маска душит резкие зоны)")
print("  ЧЕСТНО: да, знаменатель ослабляет выход в зонах высокой кривизны —")
print("  это реальная идея (edge-aware / TV-сглаживание), и она работает.\n")

# ---------- ФАКТ 4: это НЕ замена дифференциального уравнения ----------
print("="*68)
print("ФАКТ 4: 'замена дифференциальных уравнений' — проверка по определению")
print("  ОДУ задаёт ЛОКАЛЬНОЕ правило dy/dt=f(y,t) и ПОРОЖДАЕТ траекторию y(t).")
print("  Здесь Φ(t) должна быть УЖЕ ИЗВЕСТНА целиком (иначе не взять Φ', Φ'').")
print("  => формула не порождает динамику, а постобрабатывает готовый сигнал.")
print("  Нет состояния, нет обратной связи, нет эволюции. Ψ(t) — поточечная")
print("  функция от данного Φ(t). Заменить ОДУ этим нельзя в принципе.\n")

# ---------- ФАКТ 5: круговое среднее θ_local = atan2(Σsin,Σcos) ----------
print("="*68)
print("ФАКТ 5: формула θ_local = arctan(ΣsinΦ / ΣcosΦ) — корректна?")
phases = np.random.vonmises(1.0, 4.0, size=5000)   # сосредоточены вокруг 1.0
theta_local = np.arctan2(np.sin(phases).sum(), np.cos(phases).sum())
print(f"  истинное среднее направление = 1.000,  по формуле = {theta_local:.3f}")
print("  ВЕРДИКТ: это корректное КРУГОВОЕ СРЕДНЕЕ (фаза параметра порядка")
print("  Курамото). Реальная, известная математика — переоткрыта верно.\n")

# ---------- ФАКТ 6: когерентность cos(φi−φj)→1 реально кластеризует ----------
print("="*68)
print("ФАКТ 6: детекция когерентности cos(Φi−Φj)→1 (Фаза 2) — работает?")
# две синхронные группы + шумовые одиночки
g1 = 0.3 + 0.02*np.random.randn(20)
g2 = 2.5 + 0.02*np.random.randn(20)
noise_nodes = np.random.uniform(-np.pi, np.pi, 20)
ph = np.concatenate([g1, g2, noise_nodes])
M = np.cos(ph[:,None]-ph[None,:])
coh_in_g1  = M[:20,:20][np.triu_indices(20,1)].mean()
coh_g1_g2  = M[:20,20:40].mean()
coh_noise  = M[40:,40:][np.triu_indices(20,1)].mean()
print(f"  средн. cos(Δφ) внутри группы 1 : {coh_in_g1:+.3f}  (ожид ~+1)")
print(f"  средн. cos(Δφ) между гр.1 и гр.2: {coh_g1_g2:+.3f}  (ожид низкое)")
print(f"  средн. cos(Δφ) среди шумовых   : {coh_noise:+.3f}  (ожид ~0)")
print("  ВЕРДИКТ: алгоритм когерентности РЕАЛЬНО отделяет синхронные кластеры.")
print("  Это синхронизация Курамото / phase-locking — рабочая, известная вещь.")
